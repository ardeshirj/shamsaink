#!/usr/bin/env python3
"""Writes words.js from reader/ui/words.go: the interface's English and Farsi words as a list of pairs, which twins.js
uses on layout.html to draw each screen's right to left twin. Run it again after words.go changes:
    python3 docs/layouts/gen-words.py"""
import json, re, pathlib
here = pathlib.Path(__file__).parent
src = (here / '../../reader/ui/words.go').read_text()
tables = {}
for code in ('en', 'fa'):
    m = re.search(r'"%s": \{(.*?)\n\t\},' % code, src, re.S)
    tables[code] = {k: json.loads(v) for k, v in re.findall(r'"([\w-]+)":\s+(".*?"),', m.group(1))}
pairs = [[tables['en'][k], tables['fa'][k]] for k in tables['en'] if k in tables['fa']]
(here / 'words.js').write_text(
    '// Generated by gen-words.py from reader/ui/words.go: [English, Farsi] pairs, %d and %s as in Go. Do not edit.\n'
    'window.WORDS = ' + json.dumps(pairs, ensure_ascii=False) + ';\n')
print(len(pairs), 'pairs')
